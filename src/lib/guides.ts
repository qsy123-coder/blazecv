export function getGuide(slug: string): Guide | undefined {
  return GUIDES.find((guide) => guide.slug === slug);
}

export function guideHref(slug: string): string {
  return `/guides/${slug}`;
}

export function readingMinutes(guide: Guide): number {
  const chars = [
    guide.intro,
    ...guide.blocks.map((block) => {
      if (block.type === "p" || block.type === "h2" || block.type === "h3") {
        return block.text;
      }
      if (block.type === "ul" || block.type === "ol") return block.items.join("");
      if (block.type === "callout") return block.text;
      return "";
    }),
    ...guide.faq.map((item) => item.q + item.a),
  ].join("").length;
  return Math.max(3, Math.round(chars / 500));
}
